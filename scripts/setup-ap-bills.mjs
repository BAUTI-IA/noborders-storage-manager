#!/usr/bin/env node
// One-time migration for the AP / AR module — the accounts-payable side.
//
// Almost everything the section shows is DERIVED from tables that already
// exist (job balances, storage_billing, closing_sheets, expenses, storages).
// Only two things have nowhere to live today, and this migration adds them:
//
//   1. public.ap_bills — a real bill with a DUE DATE. Overhead and recurring
//      costs the CRM never modelled: storage-unit rent, insurance, phone,
//      software, loan instalments, a one-off supplier invoice. Rows with
//      source <> 'manual' are auto-generated by the app (storage rent, and the
//      next cycle of a recurring bill); the unique index makes that idempotent.
//   2. A paid_date on driver_work_days / driver_adjustments and a
//      commission_paid_date on job_extras — the app could already compute what a
//      driver is owed for a pay week, but there was no way to record that the week
//      was PAID, so the amount could never leave the payables list. All three are
//      nullable additions; nothing existing breaks.
//
// Bill attachments reuse the existing public `expense-receipts` bucket under a
// `bills/` prefix, so this migration creates no new storage bucket.
//
// DDL cannot run through the publishable/anon key (PostgREST exposes no DDL),
// so this uses the Supabase Management API, which DOES accept arbitrary SQL.
//
// Usage (Node 18+):
//   SUPABASE_ACCESS_TOKEN=sbp_xxx node scripts/setup-ap-bills.mjs
//
// Get a token at: https://supabase.com/dashboard/account/tokens
// If scripts/setup-rls.mjs was already applied, re-run it afterwards so ap_bills
// gets its per-section has_perm policies too.

const PROJECT_REF = "szkmktxziojzgfjkomua";
const TOKEN = process.env.SUPABASE_ACCESS_TOKEN;

// Keep in sync with AP_BILLS_SQL in src/App.jsx (the in-app auto-migration).
const SQL = `create table if not exists public.ap_bills (
  id bigint generated always as identity primary key,
  vendor text,
  category text,
  description text,
  amount numeric,
  amount_paid numeric default 0,
  bill_date date,
  due_date date,
  status text default 'pending',
  paid_date date,
  paid_from text default 'bank',
  bank_account text,
  recurrence text default 'once',
  recurrence_day smallint,
  parent_bill_id bigint references public.ap_bills(id) on delete set null,
  source text default 'manual',
  storage_id bigint references public.storages(id) on delete set null,
  document_url text,
  notes text,
  created_by text,
  created_at timestamptz default now(),
  updated_by text,
  updated_at timestamptz,
  deleted_at timestamptz
);
-- Auto-generated bills (storage rent, next cycle of a recurring bill) must never
-- be inserted twice: one bill per source+origin+due date.
create unique index if not exists ap_bills_autogen
  on public.ap_bills (source, storage_id, due_date) where source <> 'manual';
alter table public.ap_bills enable row level security;
drop policy if exists "ap_bills_all" on public.ap_bills;
create policy "ap_bills_all" on public.ap_bills for all to anon, authenticated using (true) with check (true);

-- Payouts to drivers: the amount was always computable, the PAID flag was not.
-- All three parts of a pay week get one, so stamping the week clears it whole.
alter table public.driver_work_days add column if not exists paid_date date;
alter table public.driver_adjustments add column if not exists paid_date date;
alter table public.job_extras add column if not exists commission_paid_date date;

do $$ begin alter publication supabase_realtime add table public.ap_bills; exception when others then null; end $$;`;

if (!TOKEN) {
  console.error("Missing SUPABASE_ACCESS_TOKEN. Run:\n  SUPABASE_ACCESS_TOKEN=sbp_xxx node scripts/setup-ap-bills.mjs");
  process.exit(1);
}

const res = await fetch(`https://api.supabase.com/v1/projects/${PROJECT_REF}/database/query`, {
  method: "POST",
  headers: { Authorization: `Bearer ${TOKEN}`, "Content-Type": "application/json" },
  body: JSON.stringify({ query: SQL }),
});

const text = await res.text();
if (res.ok) {
  console.log("✓ AP / AR listo (ap_bills + paid_date en driver_work_days y driver_adjustments + commission_paid_date en job_extras). Recargá la app y dale permisos de 'apar' a quien maneje la plata (re-corré setup-rls.mjs).");
} else {
  console.error(`✗ Error ${res.status}: ${text}`);
  process.exit(1);
}
